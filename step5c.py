import numpy as np
import pandas as pd
df = pd.read_csv("day02_usage.csv")
arr = df[["Chat","Video","Study","Games"]].to_numpy()
print()
print(arr.shape)
print()
print("Totals per App")
print(arr.sum(axis=0))
print()
print("Totals per Day")
print(arr.sum(axis=1))
print()
print("Mean per App")
print(arr.mean(axis=0).round(2))
print()
print("Mean per Day")
print(arr.mean(axis=1).round(2))
print()
print("Max per App")
print(arr.max(axis=0))
print()
print("Max per Day")
print(arr.max(axis=1))
print()
print("Min per App")
print(arr.min(axis=0))
print()
print("Min per Day")
print(arr.min(axis=1))
print()
app = np.array(["Chat","Video","Study","Games"])
winners = app[arr.argmax(axis=1)]
print(winners)
print()
vals,counts = np.unique(winners,return_counts=True)
winnerCount = dict(zip(vals.tolist(),counts.tolist()))
print(winnerCount)
print()

day_shares = (arr/(arr.sum(axis=1))[:,None]*100).round(2)
print(day_shares[0].sum())
print()
print(day_shares)
print()
app_max = (arr/(arr.max(axis=0))*100).round(2)
print(app_max)
print()
weekend = ((df["Day"]%7==6)|(df["Day"]%7==0))
print(arr[weekend].mean(axis=0))
print()
print(arr[~weekend].mean(axis=0).round(2))
print()